'use strict';

const fs = require('node:fs/promises');
const path = require('node:path');
const sharp = require('sharp');

const frontendRoot = path.resolve(__dirname, '..');
const sourceRoot = path.resolve(frontendRoot, '..', 'products/launch/media/categories/thumbnails');
const outputRoot = path.join(frontendRoot, 'src/generated/category-thumbnails');
const manifestPath = path.join(frontendRoot, 'src/generated/categoryThumbnailAssets.js');
const targetWidths = [160, 320, 480, 768];

async function main() {
  await fs.mkdir(outputRoot, { recursive: true });
  const sourceFiles = (await fs.readdir(sourceRoot))
    .filter((name) => name.toLowerCase().endsWith('.webp'))
    .sort();
  if (sourceFiles.length === 0) throw new Error(`No canonical category WebP files found in ${sourceRoot}`);

  const products = [];
  const imports = [];
  let nextId = 0;
  for (const file of sourceFiles) {
    const slug = path.basename(file, '.webp');
    const source = path.join(sourceRoot, file);
    const metadata = await sharp(source).metadata();
    if (!metadata.width || !metadata.height) throw new Error(`Invalid image dimensions: ${source}`);
    const widths = targetWidths.filter((width) => width < metadata.width);
    if (widths.length === 0) widths.push(metadata.width);
    const variants = [];

    for (const width of widths) {
      const outputName = `${slug}-${width}.webp`;
      const output = path.join(outputRoot, outputName);
      await sharp(source)
        .resize({ width, withoutEnlargement: true, fit: 'inside' })
        .webp({ quality: 82, effort: 5, alphaQuality: 90 })
        .toFile(output);
      const variable = `categoryThumbnail${nextId++}`;
      imports.push(`import ${variable} from './category-thumbnails/${outputName}';`);
      variants.push({ width, variable });
    }
    products.push({ slug, variants });
  }

  const module = [
    '// Generated by scripts/generate-category-thumbnail-assets.cjs. Do not edit.',
    ...imports,
    'export const CATEGORY_THUMBNAIL_ASSETS = {',
    ...products.map(({ slug, variants }) => `  ${JSON.stringify(slug)}: { src: ${variants[0].variable}, variants: [${variants.map(({ width, variable }) => `{ src: ${variable}, width: ${width} }`).join(', ')}] },`),
    '};',
    '',
  ].join('\n');
  await fs.mkdir(path.dirname(manifestPath), { recursive: true });
  await fs.writeFile(manifestPath, module, 'utf8');
  console.log(`Generated responsive build assets for ${sourceFiles.length} category thumbnails.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
