#!/usr/bin/env python3
"""Generate the repair selector from the canonical published product catalog."""

import csv
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / "products/launch/official/dtb_official_catalog.csv"
TAXONOMY = ROOT / "drywalltoolbox/wp/wp-content/mu-plugins/dtb-catalog-platform/Resources/catalog-taxonomy.json"
OUTPUT = ROOT / "frontend/src/data/repairCatalogOfficial.generated.js"


def main():
    with CATALOG.open(encoding="utf-8-sig", newline="") as stream:
        rows = list(csv.DictReader(stream))
    taxonomy = json.loads(TAXONOMY.read_text(encoding="utf-8"))
    labels = {item["key"]: item["label"] for item in taxonomy.get("taxa", [])}
    # These are active legacy display-category keys explicitly recognized by
    # the catalog normalizer, though their keys differ from taxonomy keys.
    labels.update({
        "handles": "Handles",
        "compound_tubes": "Compound Tubes",
        "corner_finishers": "Corner Finishers",
    })

    # Product parents are configuration containers, not selectable models.
    # Only published simple products and variations have their own selectable SKU.
    selected = [
        row for row in rows
        if row.get("Published") == "1"
        and row.get("Meta: _dtb_product_kind") == "tool"
        and row.get("Meta: _dtb_is_parts") == "0"
        and row.get("Type") in {"simple", "variation"}
    ]
    incomplete = [
        row for row in selected
        if not row.get("SKU", "").strip()
        or not row.get("Name", "").strip()
        or not row.get("Meta: _dtb_brand_label", "").strip()
        or row.get("Meta: _dtb_display_category_key", "").strip() not in labels
    ]
    if incomplete:
        raise ValueError(f"{len(incomplete)} published catalog tools have missing SKU, brand, name, or recognized display category metadata.")
    skus = [row["SKU"].strip() for row in selected]
    if len(skus) != len(set(skus)):
        raise ValueError("Duplicate SKU found among published non-parts catalog tools; refusing ambiguous repair models.")

    brands = defaultdict(lambda: defaultdict(list))
    for row in selected:
        brand = row["Meta: _dtb_brand_label"].strip()
        category_key = row["Meta: _dtb_display_category_key"].strip()
        brands[brand][labels[category_key]].append({
            "name": row["Name"].strip(),
            "sku": row["SKU"].strip(),
        })

    catalog = {"brands": {}}
    for brand in sorted(brands, key=str.casefold):
        catalog["brands"][brand] = {"modelsByCategory": {}}
        categories = brands[brand]
        for category in sorted(categories, key=str.casefold):
            models = sorted(categories[category], key=lambda model: (model["name"].casefold(), model["sku"].casefold()))
            catalog["brands"][brand]["modelsByCategory"][category] = models

    OUTPUT.write_text(
        "// Generated by scripts/catalog/generate_repair_service_catalog.py. Do not edit by hand.\n"
        "// Source: products/launch/official/dtb_official_catalog.csv + catalog-taxonomy.json.\n"
        f"export const OFFICIAL_REPAIR_CATALOG = {json.dumps(catalog, ensure_ascii=False, separators=(',', ':'))};\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"Generated {sum(len(models) for cats in catalog['brands'].values() for models in cats['modelsByCategory'].values())} repair models across {len(catalog['brands'])} brands.")


if __name__ == "__main__":
    main()
